"""Script kiểm tra và ngăn chặn ô nhiễm comment rác từ AI trong tầng source/.

Quy tắc rào chắn cứng (Lauren Tan - pstack):
1. Không cho phép các comment tạm bợ (# TODO, # TEMP, # FIX LATER, # HACK).
2. Không cho phép comment tường thuật bước làm (# Step 1: ..., # Bước 1: ...).
3. Khuyến khích mã nguồn tự tường minh (Self-documenting code) và dùng docstring chuẩn.
"""

import re
import sys
from pathlib import Path

# Thiết lập UTF-8 cho Windows console
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8")

BANNED_PATTERNS = [
    re.compile(r"#\s*(TODO|FIXME|TEMP|HACK|WORKAROUND|XXX)", re.IGNORECASE),
    re.compile(r"#\s*(Step\s*\d+|Bước\s*\d+)", re.IGNORECASE),
    re.compile(r"#\s*(AI generated|Generated by|Prompt:)", re.IGNORECASE),
    re.compile(r"#\s*(Temporary fix|Sửa tạm|Chữa cháy)", re.IGNORECASE),
]

SOURCE_DIR = Path(__file__).resolve().parent.parent / "source"


def check_file(file_path: Path) -> list[str]:
    violations: list[str] = []
    try:
        content = file_path.read_text(encoding="utf-8")
    except Exception as e:
        return [f"Khong the doc file {file_path}: {e}"]

    for line_num, line in enumerate(content.splitlines(), start=1):
        stripped = line.strip()
        # Bỏ qua dòng trống hoặc docstrings
        if not stripped or stripped.startswith(('"""', "'''")):
            continue

        for pattern in BANNED_PATTERNS:
            if pattern.search(stripped):
                violations.append(
                    f"  Line {line_num}: {stripped} (Mau cam: {pattern.pattern})"
                )

    return violations


def main() -> int:
    all_violations: dict[str, list[str]] = {}

    for py_file in SOURCE_DIR.rglob("*.py"):
        issues = check_file(py_file)
        if issues:
            rel_path = py_file.relative_to(SOURCE_DIR.parent)
            all_violations[str(rel_path)] = issues

    if all_violations:
        print("[AI COMMENT GUARDRAIL] Phat hien comment rac/tam bo trong code:")
        for path, issues in all_violations.items():
            print(f"\nFile: {path}")
            for issue in issues:
                print(issue)
        print("\nYEU CAU: Hay xoa cac comment nay. Su dung Docstring chuan.")
        return 1

    print("[AI COMMENT GUARDRAIL] Code sach, khong phat hien comment rac tu AI.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
